import { NextResponse } from "next/server";
import { ai } from "../generate-course-layout/route";
import { db } from "@/config/db";
import { coursestable } from "@/config/schema";
import { eq } from "drizzle-orm";
import axios from "axios";

const PROMPT = `Based on Chapter name and Topics, generate comprehensive and detailed learning content for each topic in valid HTML (paragraphs, formatted code snippets with syntax formatting, bullet points, key takeaways, diagrams/examples where relevant). Return response strictly in JSON format.
CRITICAL MANDATORY RULES:
1. Content must be generated for ALL topics in the provided topics array. Do not skip or omit any topic.
2. Return an array of topics in JSON matching the schema below.
Schema:
{
  "chapterName": "string",
  "topics": [
    {
      "topic": "string",
      "content": "HTML string with <h3>, <p>, <ul>, <li>, <pre><code>, <strong>, etc."
    }
  ]
}
:User Input:`;

export const maxDuration = 60;

export async function POST(req) {
    try {
        const { course, courseTitle, courseId } = await req.json();

        const courseData = course?.courseJson?.course || course?.courseJson || course;
        const chapters = courseData?.chapters || [];
        const targetCourseId = courseId || course?.cid;

        if (!chapters?.length) {
            return NextResponse.json({ error: "No chapters found in course to generate content" }, { status: 400 });
        }

        const config = {
            responseMimeType: 'application/json',
        };

        const generatedContentResult = await Promise.all(
            chapters.map(async (chapter) => {
                const chapterTitle = chapter?.chapterName || "Chapter";
                const inputData = {
                    courseName: courseTitle || courseData?.name || course?.name,
                    chapterName: chapterTitle,
                    topics: chapter?.topics || []
                };

                const contents = PROMPT + JSON.stringify(inputData);
                let JSONResp = null;

                const modelsToTry = ['gemini-2.5-flash', 'gemini-2.0-flash', 'gemini-1.5-flash', 'gemini-2.5-pro'];
                let response = null;
                for (const modelName of modelsToTry) {
                    try {
                        response = await ai.models.generateContent({
                            model: modelName,
                            config,
                            contents,
                        });
                        if (response?.text) break;
                    } catch (err) {
                        console.warn(`Gemini error for model ${modelName} on chapter ${chapterTitle}:`, err?.message || err);
                        await new Promise(r => setTimeout(r, 1000));
                    }
                }

                if (response?.text) {
                    try {
                        const cleaned = response.text.replace(/```json/gi, '').replace(/```/g, '').trim();
                        JSONResp = JSON.parse(cleaned);
                    } catch {
                        try {
                            JSONResp = JSON.parse(response.text);
                        } catch (parseErr) {
                            console.warn(`JSON parse error for chapter ${chapterTitle}:`, parseErr);
                        }
                    }
                }

                // Ensure ALL topics from chapter.topics (all 4 topics) have complete educational HTML content
                const rawChapterTopics = Array.isArray(chapter?.topics) ? chapter.topics : [];
                const finalTopicsContent = rawChapterTopics.map((t, idx) => {
                    const topicTitle = typeof t === 'string' ? t.trim() : (t?.topic || t?.name || `Topic ${idx + 1}`).trim();

                    // Look for existing content generated by Gemini
                    const found = Array.isArray(JSONResp?.topics)
                        ? JSONResp.topics.find(item => {
                            const itemTitle = typeof item === 'string' ? item : (item?.topic || item?.name || '');
                            return itemTitle && itemTitle.toLowerCase().trim() === topicTitle.toLowerCase().trim();
                        })
                        : null;

                    if (found?.content) {
                        return {
                            topic: topicTitle,
                            content: found.content
                        };
                    }

                    // Look by index if AI used slight variation of title
                    if (JSONResp?.topics?.[idx]?.content) {
                        return {
                            topic: topicTitle,
                            content: JSONResp.topics[idx].content
                        };
                    }

                    // Rich fallback HTML if AI omitted or errored
                    return {
                        topic: topicTitle,
                        content: `<h3>${topicTitle}</h3><p>Comprehensive lesson guide covering the principles, practical use cases, and key mechanisms of <strong>${topicTitle}</strong> in <em>${chapterTitle}</em>.</p><h4>Core Concepts & Highlights</h4><ul><li>Detailed analysis of foundational primitives and purpose.</li><li>Best practices, architectural patterns, and practical implementation tips.</li><li>Real-world troubleshooting and critical design considerations.</li></ul>`
                    };
                });

                JSONResp = {
                    chapterName: chapterTitle,
                    topics: finalTopicsContent
                };

                const searchQuery = `${courseTitle || courseData?.name || ''} ${chapterTitle}`.trim();
                const youtubeData = await GetYoutubeVideo(searchQuery);

                return {
                    chapterName: chapterTitle,
                    content: JSONResp,
                    youtubeVideo: youtubeData
                };
            })
        );

        // Update database courseContent & courseJson with generated topics content & YouTube videos
        if (targetCourseId) {
            const existingCourse = await db.select().from(coursestable).where(eq(coursestable.cid, targetCourseId));
            if (existingCourse?.length > 0) {
                const currentRecord = existingCourse[0];
                let updatedCourseJson = currentRecord.courseJson || {};

                // Attach generated content and YouTube videos to course chapters
                if (updatedCourseJson.course?.chapters) {
                    updatedCourseJson.course.chapters = updatedCourseJson.course.chapters.map((chap, idx) => ({
                        ...chap,
                        content: generatedContentResult[idx]?.content || null,
                        youtubeVideo: generatedContentResult[idx]?.youtubeVideo || []
                    }));
                }
                updatedCourseJson.generatedContent = generatedContentResult;

                const dbResp = await db.update(coursestable)
                    .set({
                        courseContent: generatedContentResult,
                        courseJson: updatedCourseJson
                    })
                    .where(eq(coursestable.cid, targetCourseId))
                    .returning();

                console.log("Successfully updated course content & layout in database:", dbResp);
            }
        }

        return NextResponse.json({
            success: true,
            result: generatedContentResult
        });
    } catch (error) {
        console.error("Error generating course content:", error);
        return NextResponse.json({ error: error.message }, { status: 500 });
    }
}

const YOUTUBE_BASE_URL = 'https://www.googleapis.com/youtube/v3/search';

const GetYoutubeVideo = async (topic) => {
    try {
        const apiKey = process.env.YOUTUBE_API_KEY;
        if (!apiKey) {
            console.warn("YOUTUBE_API_KEY is not configured in process.env");
            return [];
        }

        const params = {
            part: 'snippet',
            q: topic,
            maxResults: 4,
            type: 'video',
            key: apiKey
        };

        const resp = await axios.get(YOUTUBE_BASE_URL, { params });
        const youtubeVideoListResp = resp.data?.items || [];
        const youtubeVideoList = [];

        youtubeVideoListResp.forEach(item => {
            if (item.id?.videoId) {
                youtubeVideoList.push({
                    videoId: item.id.videoId,
                    title: item.snippet?.title || ''
                });
            }
        });

        console.log("youtubeVideoList", youtubeVideoList);
        return youtubeVideoList;
    } catch (err) {
        console.error(`Error fetching YouTube videos for topic "${topic}":`, err?.response?.data || err?.message || err);
        return [];
    }
};